// Verify actual saved SL-1 on an isolated in-memory SELECT snapshot. Only the
// public read flow uses the running 5175 server. No live account/session/loan writes.
import assert from 'node:assert/strict';
import { SessionRepository } from '../backend/auth.mjs';
import { LoanReadService } from '../backend/loan-reads.mjs';
import { makeServer } from '../backend/server.mjs';
import { browserHarness } from './helpers/browser-harness.mjs';
import { readSnapshot, cloneToMemory } from './helpers/readonly-snapshot.mjs';

const file=process.argv[2],liveBase='http://127.0.0.1:5175';
const before=readSnapshot(file),db=cloneToMemory(before),reads=new LoanReadService(db),requests=[];
let server,b;
try {
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM pengguna').get().n,3);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM barang').get().n,12);
  const saved=db.prepare("SELECT id_peminjaman,status FROM peminjaman WHERE kode_peminjaman='SL-1'").get();
  assert.ok(saved,'SL-1 existing harus ada, jangan diganti fixture');assert.equal(saved.status,'menunggu');
  const loan=reads.detail(saved.id_peminjaman).loan,stats=reads.stats(new URLSearchParams());
  // Valid random session generated by the existing repository on the COPY only.
  const admin=db.prepare("SELECT id_pengguna FROM pengguna WHERE peran='admin' AND aktif=1").get();
  const session=new SessionRepository(db).create(admin.id_pengguna);
  server=makeServer(db);
  server.prependListener('request',req=>requests.push({method:req.method,path:new URL(req.url,'http://test.local').pathname}));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  b=await browserHarness(base);
  const {send,evaluate,until,click,fill,screenshot,noOverflow}=b;
  await send('Network.enable');
  await send('Network.setCookie',{name:'sid',value:session.token,url:base,httpOnly:true,sameSite:'Strict'});
  await send('Page.reload');
  await until(`!!document.querySelector('[data-admin-request="${loan.id}"]')`,'SL-1 pada Dashboard Admin dari snapshot existing');
  for(const [key,value] of Object.entries({total:stats.total,waiting:stats.byStatus.menunggu,approved:stats.byStatus.disetujui,active:stats.byStatus.dipinjam,completed:stats.byStatus.selesai,rejected:stats.byStatus.ditolak,cancelled:stats.byStatus.dibatalkan})) {
    assert.equal(await evaluate(`document.querySelector('[data-admin-stat=${key}] strong').textContent`),String(value));
  }
  const statReads=requests.filter(row=>row.path==='/api/admin/loans/stats').length;
  await click('Muat Ulang Pengajuan');
  await until(`document.querySelector('[data-admin-stat=total] strong').textContent==='${stats.total}'`,'refresh statistik');
  assert.ok(requests.filter(row=>row.path==='/api/admin/loans/stats').length>statReads);
  for(const size of [{width:1440,height:900},{width:390,height:844},{width:320,height:568}]) {
    await send('Emulation.setDeviceMetricsOverride',{...size,deviceScaleFactor:1,mobile:size.width<400});
    await evaluate('window.scrollTo(0,0)');await noOverflow();await screenshot(`existing-admin-${size.width}.png`);
    await evaluate(`document.querySelector('[data-admin-detail="${loan.id}"]').click()`);
    await until(`!!document.querySelector('[data-admin-receipt="${loan.id}"]')`,'detail SL-1');
    assert.equal(await evaluate(`document.querySelector('[data-admin-receipt]').innerText.includes(${JSON.stringify(loan.number)})`),true);
    assert.equal(await evaluate(`document.querySelector('[data-admin-receipt]').innerText.includes(${JSON.stringify(loan.borrower.name)})`),true);
    assert.equal(await evaluate(`document.querySelector('[data-admin-receipt]').innerText.includes(${JSON.stringify(loan.reason)})`),true);
    for(const item of loan.items)assert.equal(await evaluate(`document.querySelector('[data-admin-receipt]').innerText.includes(${JSON.stringify(item.code+' — '+item.name+': '+item.quantity+' '+item.unit)})`),true);
    assert.equal(await evaluate("document.querySelector('[role=dialog]').innerText.includes('Belum Diverifikasi')"),true);
    assert.equal(await evaluate("[...document.querySelectorAll('[role=dialog] button')].filter(b=>['Setujui','Tolak'].includes(b.textContent)).length===2&&[...document.querySelectorAll('[role=dialog] button')].filter(b=>['Setujui','Tolak'].includes(b.textContent)).every(b=>b.disabled)"),true);
    const geometry=await evaluate("(()=>{const e=document.querySelector('[role=dialog]'),r=e.getBoundingClientRect();return {left:r.left,right:r.right,overflow:e.scrollWidth>e.clientWidth+1};})()");
    assert.ok(geometry.left>=15&&geometry.right<=size.width-15);assert.equal(geometry.overflow,false);
    await screenshot(`existing-detail-${size.width}.png`);await click('Tutup Detail Admin');
    await until("!document.querySelector('[role=dialog]')",'detail ditutup');
  }
  assert.ok(requests.some(row=>row.path===`/api/admin/loans/${loan.id}`));
  assert.equal(requests.some(row=>/\/(approve|reject)$/.test(row.path)),false);
  assert.deepEqual(db.prepare('SELECT * FROM peminjaman ORDER BY rowid').all(),before.tables.find(table=>table.name==='peminjaman').rows);

  // Remove COPY session before visiting another port (cookies are host-, not port-scoped).
  await send('Network.deleteCookies',{name:'sid',url:base});
  await send('Page.navigate',{url:liveBase});
  await until("document.body.innerText.includes('Masuk Sebagai')",'frontend aktif 5175 tanpa sesi');
  assert.equal(await evaluate("fetch('/api/admin/loans').then(r=>r.status)"),401);
  await click('Lihat Katalog & Keranjang (tanpa login)');
  await until("document.querySelectorAll('[data-catalog-item]').length===12",'12 barang pada frontend aktif');
  const liveItems=await evaluate("fetch('/api/catalog').then(r=>r.json()).then(d=>d.barang)");
  assert.deepEqual(liveItems,JSON.parse(JSON.stringify(before.tables.find(table=>table.name==='barang').rows)));
  await evaluate("(()=>{const original=window.fetch;window.__scheduleReads=[];window.fetch=async(...args)=>{const response=await original(...args);if(String(args[0]).startsWith('/api/schedule?'))window.__scheduleReads.push({url:String(args[0]),status:response.status});return response;};})()");
  await click('Jadwal Peminjaman');
  await until("!!document.querySelector('#schedule-item')",'kalender live');
  await fill('#schedule-item',String(loan.items[0].itemId));
  const scope='[aria-label="Kalender Jadwal Peminjaman"]';
  await until(`document.querySelector('${scope}').innerText.includes('Pembacaan backend:')`,'jadwal live berhasil membaca API');
  assert.equal(await evaluate(`document.querySelector('${scope}').innerText.includes('Belum diverifikasi')`),true);
  assert.equal(await evaluate(`document.querySelector('${scope}').innerText.includes('Jadwal kosong bukan bukti barang tersedia')`),true);
  assert.equal(await evaluate(`document.querySelector('${scope}').innerText.includes('SL-1')`),false,'menunggu bukan alokasi publik');
  assert.equal(await evaluate(`document.querySelector('${scope}').innerText.includes(${JSON.stringify(loan.borrower.email)})`),false,'tidak ada PII Admin pada jadwal publik');
  const scheduleReads=await evaluate('window.__scheduleReads.length');
  await click('Muat Ulang Jadwal');
  await until(`window.__scheduleReads.length>${scheduleReads}&&document.querySelector('${scope}').innerText.includes('Pembacaan backend:')`,'refresh kalender API live');
  assert.equal(await evaluate('window.__scheduleReads.every(row=>row.status===200)'),true);
  for(const size of [{width:1440,height:900},{width:390,height:844},{width:320,height:568}]) {
    await send('Emulation.setDeviceMetricsOverride',{...size,deviceScaleFactor:1,mobile:size.width<400});
    await noOverflow();await screenshot(`live-5175-schedule-${size.width}.png`);
  }
  assert.equal(readSnapshot(file).fingerprint,before.fingerprint,'Schema dan SELURUH data sumber harus identik; jangan restore jika ada perubahan sah dari proses lain.');
  console.log(JSON.stringify({result:'PASS',admin:'SL-1 + real stats/detail on isolated existing snapshot; no target login',liveFrontend:liveBase,liveChecks:'12 actual items, public schedule API + refresh, anonymous Admin 401',source:'3 accounts, 12 items, SL-1 and all schema/table contents unchanged',decisions:'BLOCKED, no requests to approve/reject',screenshots:b.profile,privacy:'Local Admin screenshots contain existing PII; do not publish.'}));
} finally {b?.close();if(server?.listening)await new Promise(resolve=>server.close(resolve));db.close();}
